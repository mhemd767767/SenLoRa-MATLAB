        function init(self)
            % init  Initialize some parameters

            self.bin_num = 2^self.sf*self.zero_padding_ratio;
            self.sample_num = 2*2^self.sf;
            self.fft_len = self.sample_num*self.zero_padding_ratio;

            self.downchirp = LoRaPHY.chirp(false, self.sf, self.bw, 2*self.bw, 0, self.cfo, 0);
            self.upchirp = LoRaPHY.chirp(true, self.sf, self.bw, 2*self.bw, 0, self.cfo, 0);

            % Low Data Rate Optimization (LDRO) mode in LoRa
            % If the chirp peird is larger than 16ms, the least significant
            % two bits are considered unreliable and are neglected.
            if 2^(self.sf)/self.bw > 16e-3
                self.ldr = 1;
            else
                self.ldr = 0;
            end
        end

        function pk = dechirp(self, x, is_up)
            % dechirp  Apply dechirping on the symbol starts from index x
            %
            % input:
            %     x: Start index of a symbol
            %     is_up: `true` if applying up-chirp dechirping
            %            `false` if applying down-chirp dechirping
            % output:
            %     pk: Peak in FFT results of dechirping
            %         pk = (height, index)

            if nargin == 3 && ~is_up
                c = self.upchirp;
            else
                c = self.downchirp;
            end
            ft = fft(self.sig(x:x+self.sample_num-1).*c, self.fft_len);
            ft_ = abs(ft(1:self.bin_num)) + abs(ft(self.fft_len-self.bin_num+1:self.fft_len));
            pk = LoRaPHY.topn([ft_ (1:self.bin_num).'], 1);
        end

        function x = detect(self, start_idx)
            % detect  Detect preamble
            %
            % input:
            %     start_idx: Start index for detection
            % output:
            %     x: Before index x, a preamble is detected.
            %        x = -1 if no preamble detected

            ii = start_idx;
            pk_bin_list = []; % preamble peak bin list
            while ii < length(self.sig)-self.sample_num*self.preamble_len
                % search preamble_len-1 basic upchirps
                if length(pk_bin_list) == self.preamble_len - 1
                    % preamble detected
                    % coarse alignment: first shift the up peak to position 0
                    % current sampling frequency = 2 * bandwidth
                    x = ii - round((pk_bin_list(end)-1)/self.zero_padding_ratio*2);
                    return;
                end
                pk0 = self.dechirp(ii);
                if ~isempty(pk_bin_list)
                    bin_diff = mod(pk_bin_list(end)-pk0(2), self.bin_num);
                    if bin_diff > self.bin_num/2
                        bin_diff = self.bin_num - bin_diff;
                    end
                    if bin_diff <= self.zero_padding_ratio
                        pk_bin_list = [pk_bin_list; pk0(2)];
                    else
                        pk_bin_list = pk0(2);
                    end
                else
                    pk_bin_list = pk0(2);
                end
                ii = ii + self.sample_num;
            end
            x = -1;
        end

        function s = modulate(self, symbols)
            % modulate  Modulate a baseband signal
            %
            % input:
            %     symbols: A vector of chirp symbols to be modulated
            %              valid symbol range: 0 to 2^sf-1
            % output:
            %     s: A valid LoRa baseband signal

            uc = LoRaPHY.chirp(true, self.sf, self.bw, self.fs, 0, self.cfo, 0);
            dc = LoRaPHY.chirp(false, self.sf, self.bw, self.fs, 0, self.cfo, 0);
            preamble = repmat(uc, self.preamble_len, 1);
            netid = [LoRaPHY.chirp(true, self.sf, self.bw, self.fs, 24, self.cfo, 0); LoRaPHY.chirp(true, self.sf, self.bw, self.fs, 32, self.cfo, 0)];

            chirp_len = length(uc);
            sfd = [dc; dc; dc(1:round(chirp_len/4))];
            data = zeros(length(symbols)*chirp_len, 1);
            for i = 1:length(symbols)
                data((i-1)*chirp_len+1:i*chirp_len) =  LoRaPHY.chirp(true, self.sf, self.bw, self.fs, symbols(i), self.cfo, 0);
            end
            s = [preamble; netid; sfd; data];
        end

        function symbols = encode(self, payload)
            % encode  Encode bytes to symbols
            %
            % input:
            %     payload: Payload of LoRa packet
            % output:
            %     symbols: A vector representing the symbols of the packet

            if self.crc
                data = uint8([payload; self.calc_crc(payload)]);
            else
                data = uint8(payload);
            end

            plen = length(payload);
            sym_num = self.calc_sym_num(plen);
            % filling all symbols needs nibble_num nibbles
            nibble_num = self.sf - 2 + (sym_num-8)/(self.cr+4)*(self.sf-2*self.ldr);
            data_w = uint8([data; 255*ones(ceil((nibble_num-2*length(data))/2), 1)]);
            data_w(1:plen) = self.whiten(data_w(1:plen));
            data_nibbles = uint8(zeros(nibble_num, 1));
            for i = 1:nibble_num
                idx = ceil(i/2);
                if mod(i, 2) == 1
                    data_nibbles(i) = bitand(data_w(idx), 0xf);
                else
                    data_nibbles(i) = bitshift(data_w(idx), -4);
                end
            end

            if self.has_header
                header_nibbles = self.gen_header(plen);
            else
                header_nibbles = [];
            end
            codewords = self.hamming_encode([header_nibbles; data_nibbles]);

            % interleave
            % first 8 symbols use CR=4/8
            symbols_i = self.diag_interleave(codewords(1:self.sf-2), 8);
            ppm = self.sf - 2*self.ldr;
            rdd = self.cr + 4;
            for i = self.sf-1:ppm:length(codewords)-ppm+1
                symbols_i = [symbols_i; self.diag_interleave(codewords(i:i+ppm-1), rdd)];
            end

            symbols = self.gray_decoding(symbols_i);
        end

        function header_nibbles = gen_header(self, plen)
            % gen_header  Generate a valid LoRa header
            %
            % input:
            %     plen: Payload length
            % output:
            %     header_nibbles: Header in nibbles

            header_nibbles = zeros(5, 1);
            header_nibbles(1) = bitshift(plen, -4);
            header_nibbles(2) = bitand(plen, 15);
            header_nibbles(3) = bitor(2*self.cr, self.crc);
            header_checksum = self.header_checksum_matrix * gf(reshape(de2bi(header_nibbles(1:3), 4, 'left-msb')', [], 1));
            x = header_checksum.x;
            header_nibbles(4) = x(1);
            for i = 1:4
                header_nibbles(5) = bitor(header_nibbles(5), x(i+1)*2^(4-i));
            end
        end

        function checksum = calc_crc(self, data)
            % calc_crc  Calculate payload CRC
            %
            % input:
            %     data: Data in bytes
            % output:
            %     checksum: CRC result

            switch length(data)
                case 0
                    checksum = [0; 0];
                case 1
                    checksum = [data(end); 0];
                case 2
                    checksum = [data(end); data(end-1)];
                otherwise
                    input = data(1:end-2);
                    seq = self.crc_generator(reshape(logical(de2bi(input, 8, 'left-msb'))', [], 1));
                    checksum_b1 = bitxor(bi2de(seq(end-7:end)', 'left-msb'), data(end));
                    checksum_b2 = bitxor(bi2de(seq(end-15:end-8)', 'left-msb'), data(end-1));
                    checksum = [checksum_b1; checksum_b2];
            end
        end

        function data_w = whiten(self, data)
            % whiten  Whitening process in LoRa
            %
            % input:
            %     data: Data in bytes
            % output:
            %     data_w: Data after whitening

            len = length(data);
            data_w = bitxor(data(1:len), self.whitening_seq(1:len));
            self.print_bin("Whiten", data_w);
        end

        function codewords = hamming_encode(self, nibbles)
            % hamming_encode  Hamming encoding process in LoRa
            %
            % input:
            %     nibbles: Data in nibbles
            % output:
            %     codewords: Data after hamming encoding

            nibble_num = length(nibbles);
            codewords = uint8(zeros(nibble_num, 1));
            for i = 1:nibble_num
                nibble = nibbles(i);

                p1 = LoRaPHY.bit_reduce(@bitxor, nibble, [1 3 4]);
                p2 = LoRaPHY.bit_reduce(@bitxor, nibble, [1 2 4]);
                p3 = LoRaPHY.bit_reduce(@bitxor, nibble, [1 2 3]);
                p4 = LoRaPHY.bit_reduce(@bitxor, nibble, [1 2 3 4]);
                p5 = LoRaPHY.bit_reduce(@bitxor, nibble, [2 3 4]);
                if i <= self.sf - 2
                    % the first SF-2 nibbles use CR=4/8
                    cr_now = 4;
                else
                    cr_now = self.cr;
                end
                switch cr_now
                    case 1
                        codewords(i) = bitor(uint8(p4)*16, nibble);
                    case 2
                        codewords(i) = LoRaPHY.word_reduce(@bitor, [uint8(p5)*32 uint8(p3)*16 nibble]);
                    case 3
                        codewords(i) = LoRaPHY.word_reduce(@bitor, [uint8(p2)*64 uint8(p5)*32 uint8(p3)*16 nibble]);
                    case 4
                        codewords(i) = LoRaPHY.word_reduce(@bitor, [uint8(p1)*128 uint8(p2)*64 uint8(p5)*32 uint8(p3)*16 nibble]);
                    otherwise
                        % THIS CASE SHOULD NOT HAPPEN
                        error('Invalid Code Rate!');
                end
            end
        end

        function symbols_i = diag_interleave(self, codewords, rdd)
            % diag_interleave  Diagonal interleaving
            %
            % input:
            %     codewords: Data in nibbles
            %     rdd: Bits with redundancy
            %          For example, code rate 4/5 means rdd = 5
            % output:
            %     symbols_i: Symbols after diagonal interleaving

            tmp = de2bi(codewords, rdd, 'right-msb');
            symbols_i = uint16(bi2de(cell2mat(arrayfun(@(x) circshift(tmp(:,x), 1-x), 1:rdd, 'un', 0))'));
            self.print_bin("Interleave", symbols_i);
        end

        function symbols = gray_decoding(self, symbols_i)
            % gray_decoding  Gray decoding
            %                `gray_decoding` is used in the ENCODING process
            %
            % input:
            %     symbols_i: Interleaved symbols
            % output:
            %     symbols: Final symbols to be modulated in a packet

            symbols = zeros(length(symbols_i), 1);
            for i = 1:length(symbols_i)
                num = uint16(symbols_i(i));
                mask = bitshift(num, -1);
                while mask ~= 0
                    num = bitxor(num, mask);
                    mask = bitshift(mask, -1);
                end
                if i <= 8 || self.ldr
                    symbols(i) = mod(num * 4 + 1, 2^self.sf);
                else
                    symbols(i) = mod(num + 1, 2^self.sf);
                end
            end
        end

        function sym_num = calc_sym_num(self, plen)
            % calc_sym_num  Calculate number of symbols
            %
            % input:
            %     plen: Payload length
            % output:
            %     sym_num: Number of symbols

            sym_num = double(8 + max((4+self.cr)*ceil(double((2*plen-self.sf+7+4*self.crc-5*(1-self.has_header)))/double(self.sf-2*self.ldr)), 0));
        end

        function x_sync = sync(self, x)
            % sync  Packet synchronization
            %
            % input:
            %     x: Start index for synchronization
            % output:
            %     x_sync: Index after up-down alignment

            % find downchirp
            found = false;
            while x < length(self.sig) - self.sample_num
                up_peak = self.dechirp(x);
                down_peak = self.dechirp(x, false);
                if abs(down_peak(1)) > abs(up_peak(1))
                    % downchirp detected
                    found = true;
                end
                x = x + self.sample_num;
                if found
                    break;
                end
            end

            if ~found
                return;
            end

            % Up-Down Alignment
            % NOTE preamble_len >= 6
            % NOTE there are two NETID chirps between preamble and SFD
            % NOTE `detect` has already shifted the up peak to position 0
            pkd = self.dechirp(x, false);
            if pkd(2) > self.bin_num / 2
                to = round((pkd(2)-1-self.bin_num)/self.zero_padding_ratio);
            else
                to = round((pkd(2)-1)/self.zero_padding_ratio);
            end
            x = x + to;

            % set preamble reference bin for CFO elimination
            pku = self.dechirp(x - 4*self.sample_num);
            self.preamble_bin = pku(2);

            if self.preamble_bin > self.bin_num / 2
                self.cfo = (self.preamble_bin-self.bin_num-1)*self.bw/self.bin_num;
            else
                self.cfo = (self.preamble_bin-1)*self.bw/self.bin_num;
            end

            % set x to the start of data symbols
            pku = self.dechirp(x-self.sample_num);
            pkd = self.dechirp(x-self.sample_num, false);
            if abs(pku(1)) > abs(pkd(1))
                % current symbol is the first downchirp
                x_sync = x + round(2.25*self.sample_num);
            else
                % current symbol is the second downchirp
                x_sync = x + round(1.25*self.sample_num);
            end
        end

        function symbols = dynamic_compensation(self, data)
            % dynamic_compensation  Compensate bin drift
            %
            % input:
            %     data: Symbols with bin drift
            % output:
            %     symbols: Symbols after bin calibration

            % compensate the bin drift caused by Sampling Frequency Offset (SFO)
            sfo_drift = (1 + (1:length(data))') * 2^self.sf * self.cfo / self.rf_freq;
            symbols = mod(data - sfo_drift, 2^self.sf);

            if self.ldr
                bin_offset = 0;
                v_last = 1;

                for i = 1:length(symbols)
                    v = symbols(i);
                    bin_delta = mod(v-v_last, 4);
                    if bin_delta < 2
                        bin_offset = bin_offset - bin_delta;
                    else
                        bin_offset = bin_offset - bin_delta + 4;
                    end
                    v_last = v;
                    symbols(i) = mod(v+bin_offset, 2^self.sf);
                end
            end
        end

        function bytes_w = dewhiten(self, bytes)
            % dewhiten  Data Dewhitening
            %
            % input:
            %     bytes: Bytes after deinterleaving
            % output:
            %     bytes_w: Bytes after dewhitening

            len = length(bytes);
            bytes_w = bitxor(uint8(bytes(1:len)), self.whitening_seq(1:len));
            self.print_bin("Dewhiten", bytes_w);
        end

        function time_ms = time_on_air(self, plen)
            % time_on_air  Calculate the flying time of a LoRa packet
            %
            % input:
            %     plen: Payload length
            % output:
            %     time_ms: Flying time (in milliseconds)

            sym_num = self.calc_sym_num(plen);
            % milliseconds
            time_ms = (sym_num + 4.25 + self.preamble_len) * (2^self.sf/self.bw) * 1000;
        end

        function print_bin(self, flag, vec, size)
            if self.is_debug
                if nargin == 3
                    size = 8;
                end
                len = length(vec);
                fprintf("%s:\n", flag);
                for i = 1:len
                    fprintf("%s\n", dec2bin(round(vec(i)), size));
                end
                fprintf("\n");
            end
        end

        function [spectra, raw_symbols] = soft_capture_fft(self, x, n_symbols)
            %SOFT_CAPTURE_FFT Complex dechirped FFT Z[f] (Eq. 3).
            %   LoRaPHY works at 2*BW samples/s. Sample alternate dechirped
            %   IQ points to form 2^SF samples at BW for the 2^SF-bin FFT.
            %   Keep the zero-padded folded FFT for coarse alignment.
            M = 2^self.sf;
            spectra = complex(zeros(M, n_symbols));
            raw_symbols = zeros(n_symbols,1);
            for j = 1:n_symbols
                start_idx = x + (j-1)*self.sample_num;
                samples = self.sig(start_idx:start_idx+self.sample_num-1);
                D = samples.*self.downchirp;
                spectra(:,j) = fft(D(1:2:end), M);
                ft = fft(D, self.fft_len);
                folded = abs(ft(1:self.bin_num)) + ...
                    abs(ft(self.fft_len-self.bin_num+1:self.fft_len));
                [~, pk_index] = max(folded);
                raw_symbols(j) = mod((pk_index+self.bin_num - ...
                    self.preamble_bin)/self.zero_padding_ratio, ...
                    2^self.sf);
            end
        end

        function symbol_llr = soft_fft_to_llr(self, spectra, raw, corrected, ...
                is_header)
            %SOFT_FFT_TO_LLR FFT-bin probability -> Gray-bit LLRs.
            %   Equation (12): P(f) = exp(|Z(f)|^2-N0)/sum(exp(...)).
            %   N0 and the common normalization cancel in Eq. (13).
            %   The FFT data here are complex and are NOT rescaled.
            M = 2^self.sf;
            n_symbols = size(spectra,2);
            if is_header || self.ldr
                ppm = self.sf-2;
                gray_input = floor((0:M-1)/4);
            else
                ppm = self.sf;
                gray_input = mod((0:M-1)-1,M);
            end
            g = bitxor(uint16(gray_input), ...
                bitshift(uint16(gray_input), -1));
            symbol_llr = zeros(n_symbols, ppm);
            candidates = 0:M-1;
            preamble_shift = (self.preamble_bin-1)/self.zero_padding_ratio;
            for j = 1:n_symbols
                % Shift physical FFT candidates using the original LoRaPHY
                % preamble CFO and dynamic SFO alignment estimates.
                correction = mod(raw(j)-corrected(j)+M/2,M)-M/2;
                idx = mod(round(candidates+preamble_shift+correction),M)+1;
                Z = spectra(idx,j);
                energy = abs(Z).^2;
                for b = 1:ppm
                    ones_mask = (bitget(g, ppm-b+1)==1);
                    e1 = energy(ones_mask);
                    e0 = energy(~ones_mask);
                    max1 = max(e1);
                    max0 = max(e0);
                    logp1 = max1 + log(sum(exp(e1-max1)));
                    logp0 = max0 + log(sum(exp(e0-max0)));
                    symbol_llr(j,b) = logp1 - logp0;
                end
            end
        end

        function word_llr = soft_diag_deinterleave(self, symbol_llr) %#ok<INUSD>
            %SOFT_DIAG_DEINTERLEAVE Reverse the ORIGINAL LoRaPHY bit routing.
            %   Rows of input: transmitted chirps (4+CR).
            %   Columns of input: Gray-mapped bits in left-MSB order.
            %   Rows of output: Hamming codewords (SF or SF-2).
            %   Columns of output: codeword bits in left-MSB order.
            rdd = size(symbol_llr,1);
            rearranged = zeros(size(symbol_llr));
            for row = 1:rdd
                rearranged(row,:) = circshift(symbol_llr(row,:), ...
                    [0, 1-row]);
            end
            word_llr = fliplr(flipud(rearranged.'));
        end

        function [decode_words, scores, nibbles] = soft_hamming_block( ...
                self, word_llr, CR)
            %SOFT_HAMMING_BLOCK Algorithm 1 squared-LLR candidate scoring.
            %   Uses cached, fixed SenLoRa Table 3 values converted once
            %   into LoRaPHY's own codeword bit order.
            [candidate_bits, candidate_values] = ...
                self.soft_hamming_codebook(CR);
            if size(word_llr,2) ~= 4+CR
                error('Soft Hamming input must have 4+CR LLR columns.');
            end
            weighted = sign(word_llr).*(word_llr.^2);
            candidate_sign = 2*candidate_bits-1;
            all_scores = weighted*candidate_sign.';
            [scores, idx] = max(all_scores,[],2);
            decode_words = candidate_values(idx);
            nibbles = uint8(bitand(decode_words, 15));
        end

        function [candidate_bits, candidate_values] = ...
                soft_hamming_codebook(self, CR) %#ok<INUSD>
            %SOFT_HAMMING_CODEBOOK SenLoRa Table 3, cached lookup.
            %   Table 3 prints data nibble first and parity nibble second.
            %   LoRaPHY stores its nibble in the lowest four bits and has
            %   a different data-bit order in its parity equations.
            %   Reorder the nibble-bit indices and parity once, then cache.
            persistent fixed_bits fixed_values
            if ~ismember(CR,1:4)
                error('CR must be 1, 2, 3, or 4.');
            end
            if isempty(fixed_values)
                % Exact 16-entry CR=1 table in SenLoRa Table 3.
                table_cr1 = uint16([ ...
                    0 24 40 48 72 80 96 120 ...
                    136 144 160 184 192 216 232 240]);
                % Exact 16-entry CR=2,3,4 table in SenLoRa Table 3.
                table_cr234 = uint16([ ...
                    0 23 45 58 78 89 99 116 ...
                    139 156 166 177 197 210 232 255]);

                nibbles = uint16((0:15)');
                table_nibbles = bitor( ...
                    bitor(bitshift(bitand(nibbles,1),1), ...
                          bitshift(bitand(nibbles,2),-1)), ...
                    bitor(bitshift(bitand(nibbles,4),1), ...
                          bitshift(bitand(nibbles,8),-1)));
                table_indices = double(table_nibbles)+1;
                fixed_bits = cell(1,4);
                fixed_values = cell(1,4);
                for r = 1:4
                    if r == 1
                        parity = bitshift(bitand(table_cr1(table_indices),15),-3);
                    else
                        parity = bitand(table_cr234(table_indices),2^r-1);
                    end
                    values = bitor(nibbles,bitshift(parity,4));
                    fixed_values{r} = values;
                    fixed_bits{r} = double(dec2bin(values,4+r)-'0');
                end
            end
            candidate_bits = fixed_bits{CR};
            candidate_values = fixed_values{CR};
        end

        function is_valid = soft_parse_header(self, nibbles)
            %SOFT_PARSE_HEADER Mirror the unchanged parse_header() checks.
            is_valid = false;
            if numel(nibbles) < 5
                return;
            end
            payload_len = double(nibbles(1)*16+nibbles(2));
            has_crc = double(bitand(nibbles(3),1));
            cr = double(bitshift(nibbles(3),-1));
            if ~ismember(cr,1:4)
                return;
            end
            checksum = [bitand(nibbles(4),1); ...
                de2bi(nibbles(5),4,'left-msb')'];
            checksum_calc = self.header_checksum_matrix* ...
                gf(reshape(de2bi(nibbles(1:3),4,'left-msb')',[],1));
            if any(checksum ~= checksum_calc)
                return;
            end
            self.payload_len = payload_len;
            self.crc = has_crc;
            self.cr = cr;
            is_valid = true;
        end

        function [data_m, checksum_m, info] = iterative_soft_receive(self, sig, max_iter, opts)
            %ITERATIVE_SOFT_RECEIVE SenLoRa Algorithm 2 research implementation.
            %   [DATA, CHECKSUM, INFO] = ITERATIVE_SOFT_RECEIVE(PHY, IQ, 5)
            %   The published paper does not specify the actual amendLLR()
            %   or channelSense() formulas. 
            %   INFO(iter).history(m) gives selected pilot indices, block
            %   thresholds, global thresholds, and estimated channel gains.
            %   INFO(iter).decoded_codewords is compatible with the Phase 1
            %   coded-symbol SER reconstruction test.
            %
            %   OPTS fields: alpha (0.8), llr_feedback_gain (0.25),
            %   channel_relaxation (0.5), pilot_fallback (false).
            if nargin < 3 || isempty(max_iter)
                max_iter = 5;
            end
            validateattributes(max_iter, {'numeric'}, ...
                {'scalar','integer','positive','finite'}, mfilename, 'max_iter');
            if nargin < 4 || isempty(opts)
                opts = struct();
            end
            if ~isstruct(opts) || ~isscalar(opts)
                error('OPTS must be a scalar struct.');
            end
            if ~isfield(opts,'alpha'), opts.alpha = 0.8; end
            if ~isfield(opts,'llr_feedback_gain')
                opts.llr_feedback_gain = 0.25;
            end
            if ~isfield(opts,'channel_relaxation')
                opts.channel_relaxation = 0.5;
            end
            if ~isfield(opts,'pilot_fallback')
                opts.pilot_fallback = false;
            end
            validateattributes(opts.alpha,{'numeric'}, ...
                {'scalar','real','>=',0,'<=',1});
            validateattributes(opts.llr_feedback_gain,{'numeric'}, ...
                {'scalar','real','>=',0,'<=',1});
            validateattributes(opts.channel_relaxation,{'numeric'}, ...
                {'scalar','real','>=',0,'<=',1});
            if ~isscalar(opts.pilot_fallback)
                error('OPTS.pilot_fallback must be scalar logical.');
            end

            self.cfo = 0;
            self.init();
            if ~self.fast_mode
                sig = lowpass(sig, self.bw/2, self.fs);
            end
            self.sig = resample(sig, 2*self.bw, self.fs);

            data_m = [];
            checksum_m = [];
            info = struct('decoded_codewords',{}, 'codeword_scores',{}, ...
                'symbol_llr',{}, 'amended_symbol_llr',{}, ...
                'confidence',{}, 'selected_symbols',{}, ...
                'channel_estimate',{}, 'iterations',{}, ...
                'converged',{}, 'history',{}, 'header_valid',{}, ...
                'packet_start_sample',{}, 'packet_cfo_hz',{}, ...
                'packet_num_symbols',{}, 'packet_cr',{});
            cursor = 1;
            M = 2^self.sf;
            while cursor < length(self.sig)
                x = self.detect(cursor);
                if x < 0
                    break;
                end
                x = self.sync(x);
                if x > length(self.sig)-8*self.sample_num+1
                    break;
                end
                [header_spec,header_raw] = self.soft_capture_fft(x,8);
                header_corr = self.dynamic_compensation(header_raw);
                header_llr = self.soft_fft_to_llr(header_spec, ...
                    header_raw,header_corr,true);
                [header_codes,header_scores,header_nibbles] = ...
                    self.soft_hamming_block( ...
                    self.soft_diag_deinterleave(header_llr),4);
                if self.has_header
                    header_ok = self.soft_parse_header(header_nibbles);
                else
                    header_ok = ~isempty(self.payload_len) && ...
                        ~isempty(self.cr);
                end
                if ~header_ok
                    cursor = x+7*self.sample_num;
                    continue;
                end
                n_symbols = self.calc_sym_num(self.payload_len);
                if x > length(self.sig)-n_symbols*self.sample_num+1
                    break;
                end

                samples = reshape( ...
                    self.sig(x:x+n_symbols*self.sample_num-1), ...
                    self.sample_num,n_symbols);
                [~,raw] = self.soft_capture_fft(x,n_symbols);
                corrected = self.dynamic_compensation(raw);
                h_hat = complex(ones(1,n_symbols));
                previous_selected = false(n_symbols,1);
                global_threshold = NaN;
                converged = false;
                history = struct('selected_symbols',{},'confidence',{}, ...
                    'block_thresholds',{},'global_thresholds',{}, ...
                    'channel_estimate',{},'decoded_codewords',{});
                nibbles = uint8([]);
                scores = [];
                decoded_codes = uint16([]);
                llr = zeros(n_symbols,self.sf);
                amended_llr = zeros(n_symbols,self.sf);
                confidence = nan(n_symbols,1);
                selected = false(n_symbols,1);
                reconstructed_symbols = nan(n_symbols,1);
                rdd = self.cr+4;
                ppm = self.sf-2*self.ldr;
                nBlocks = (n_symbols-8)/rdd;

                for iter = 1:max_iter
                    % Equalize using the previous estimated flat complex
                    % channel gain for each chirp, then use Eq. (3).
                    equalized = samples ./ reshape(h_hat,1,[]);
                    D = equalized .* self.downchirp;
                    spectra = fft(D(1:2:end,:),M,1);
                    llr(:) = 0;
                    llr(1:8,1:self.sf-2) = header_llr;
                    if n_symbols > 8
                        data_llr = self.soft_fft_to_llr( ...
                            spectra(:,9:end),raw(9:end), ...
                            corrected(9:end),false);
                        llr(9:end,1:ppm) = data_llr;
                    end

                    if self.has_header
                        nibbles = uint8(header_nibbles(6:end));
                    else
                        nibbles = uint8(header_nibbles);
                    end
                    decoded_codes = uint16(header_codes(:));
                    scores = header_scores(:);
                    amended_llr(:) = 0;
                    amended_llr(1:8,1:self.sf-2) = header_llr;
                    confidence(:) = NaN;
                    selected(:) = false;
                    reconstructed_symbols(:) = NaN;
                    block_thresholds = nan(nBlocks,1);
                    global_thresholds = nan(nBlocks,1);

                    for block = 1:nBlocks
                        ii = 9+(block-1)*rdd;
                        chirp_range = ii:ii+rdd-1;
                        word_llr = self.soft_diag_deinterleave( ...
                            llr(chirp_range,1:ppm));
                        [codes,block_scores,decoded_nibbles] = ...
                            self.soft_hamming_block(word_llr,self.cr);
                        nibbles = [nibbles;decoded_nibbles(:)]; %#ok<AGROW>
                        decoded_codes = [decoded_codes;uint16(codes(:))]; %#ok<AGROW>
                        scores = [scores;block_scores(:)]; %#ok<AGROW>

                        % Paper's amendLLR() is unspecified: this bounded
                        % feedback reinforces codeword decisions using
                        % their normalized Algorithm 1 winning scores.
                        amended_words = self.senlora_amend_llr( ...
                            word_llr,codes,block_scores, ...
                            opts.llr_feedback_gain);
                        amended_symbols = self.senlora_reinterleave_llr( ...
                            amended_words);
                        amended_llr(chirp_range,1:ppm) = amended_symbols;
                        block_conf = sum(abs(amended_symbols).^2,2);
                        confidence(chirp_range) = block_conf;
                        tau_b = mean(block_conf)+std(block_conf);
                        if isnan(global_threshold)
                            global_threshold = tau_b;
                        else
                            global_threshold = opts.alpha*global_threshold + ...
                                (1-opts.alpha)*tau_b;
                        end
                        block_thresholds(block) = tau_b;
                        global_thresholds(block) = global_threshold;
                        confident = block_conf >= global_threshold;
                        if ~any(confident) && opts.pilot_fallback
                            [~,largest] = max(block_conf);
                            confident(largest) = true;
                        end
                        selected(chirp_range) = confident;
                        reconstructed_symbols(chirp_range) = ...
                            self.senlora_chirps_from_codewords(codes);
                    end

                    history(iter).selected_symbols = find(selected);
                    history(iter).confidence = confidence;
                    history(iter).block_thresholds = block_thresholds;
                    history(iter).global_thresholds = global_thresholds;
                    history(iter).channel_estimate = h_hat;
                    history(iter).decoded_codewords = decoded_codes;

                    if iter > 1 && isequal(selected,previous_selected)
                        converged = true;
                        break;
                    end
                    if ~any(selected)
                        % No accepted soft pilots: no channel update possible.
                        break;
                    end
                    if iter < max_iter
                        h_hat = self.senlora_refine_flat_channel( ...
                            samples,reconstructed_symbols,selected,h_hat, ...
                            opts.channel_relaxation);
                    end
                    previous_selected = selected;
                end

                num_bytes = min(255,floor(numel(nibbles)/2));
                bytes = zeros(num_bytes,1,'uint8');
                for ii = 1:num_bytes
                    bytes(ii) = bitor(uint8(nibbles(2*ii-1)), ...
                        bitshift(uint8(nibbles(2*ii)),4));
                end
                len = self.payload_len;
                if len+2*self.crc > numel(bytes)
                    cursor = x+n_symbols*self.sample_num;
                    continue;
                end
                if self.crc
                    data = [self.dewhiten(bytes(1:len)); ...
                        bytes(len+1:len+2)];
                    checksum = self.calc_crc(data(1:len));
                else
                    data = self.dewhiten(bytes(1:len));
                    checksum = [];
                end
                data_m = [data_m data]; %#ok<AGROW>
                checksum_m = [checksum_m checksum]; %#ok<AGROW>
                report.decoded_codewords = decoded_codes;
                report.codeword_scores = scores;
                report.symbol_llr = llr;
                report.amended_symbol_llr = amended_llr;
                report.confidence = confidence;
                report.selected_symbols = find(selected);
                report.channel_estimate = h_hat;
                report.iterations = iter;
                report.converged = converged;
                report.history = history;
                report.header_valid = header_ok;
                report.packet_start_sample = x;
                report.packet_cfo_hz = self.cfo;
                report.packet_num_symbols = n_symbols;
                report.packet_cr = self.cr;
                info(end+1) = report; %#ok<AGROW>
                cursor = x+n_symbols*self.sample_num;
            end
        end

        function amended = senlora_amend_llr(self,word_llr,codes,scores,gain) %#ok<INUSD>
            %SENLORA_AMEND_LLR Bounded feedback; paper omits this formula.
            rdd = size(word_llr,2);
            bits = double(dec2bin(uint16(codes(:)),rdd)-'0');
            desired_signs = 2*bits-1;
            power = sum(abs(word_llr).^2,2);
            reliability = max(0,min(1,double(scores(:))./max(power,eps)));
            correction = gain.*reliability.*mean(abs(word_llr),2);
            amended = word_llr + bsxfun(@times,desired_signs,correction);
        end

        function sym_llr = senlora_reinterleave_llr(self,word_llr) %#ok<INUSD>
            %SENLORA_REINTERLEAVE_LLR Inverse of soft_diag_deinterleave.
            tmp = fliplr(flipud(word_llr)).';
            rdd = size(tmp,1);
            sym_llr = zeros(size(tmp));
            for row = 1:rdd
                sym_llr(row,:) = circshift(tmp(row,:),[0,row-1]);
            end
        end

        function symbols = senlora_chirps_from_codewords(self,codes)
            %SENLORA_CHIRPS_FROM_CODEWORDS Payload interleaving + Gray map.
            %   Do not call gray_decoding() on a stand-alone payload block:
            %   its first eight input positions are always treated as header.
            mapped = self.diag_interleave(uint16(codes(:)),self.cr+4);
            symbols = zeros(numel(mapped),1);
            M = 2^self.sf;
            for jj = 1:numel(mapped)
                num = uint16(mapped(jj));
                mask = bitshift(num,-1);
                while mask ~= 0
                    num = bitxor(num,mask);
                    mask = bitshift(mask,-1);
                end
                if self.ldr
                    symbols(jj) = mod(double(num)*4+1,M);
                else
                    symbols(jj) = mod(double(num)+1,M);
                end
            end
        end

        function h_new = senlora_refine_flat_channel( ...
                self,rx_chirps,symbols,selected,h_old,relaxation)
            %SENLORA_REFINE_FLAT_CHANNEL Scalar LS from decoded soft pilots.
            %   h_j = sum(conj(reference_j).*received_j) / ||reference_j||^2
            %   Interpolate complex h_j between selected chirps. This is a
            %   flat-fading approximation to paper's unspecified channelSense.
            positions = find(selected);
            h_new = h_old;
            if isempty(positions)
                return;
            end
            gains = complex(zeros(size(positions)));
            for jj = 1:numel(positions)
                pos = positions(jj);
                reference = LoRaPHY.chirp(true,self.sf,self.bw, ...
                    2*self.bw,double(symbols(pos)),0,0);
                gains(jj) = sum(conj(reference).*rx_chirps(:,pos)) / ...
                    max(sum(abs(reference).^2),eps);
            end
            valid = isfinite(real(gains)) & isfinite(imag(gains)) & ...
                abs(gains)>0.05;
            positions = positions(valid);
            gains = gains(valid);
            if isempty(positions)
                return;
            end
            if numel(positions)==1
                fitted = repmat(gains,1,numel(h_old));
            else
                query = 1:numel(h_old);
                fitted = interp1(double(positions),real(gains),query, ...
                    'linear','extrap') + 1i*interp1(double(positions), ...
                    imag(gains),query,'linear','extrap');
            end
            mag = abs(fitted);
            fitted = fitted .* (max(0.05,min(20,mag))./max(mag,eps));
            h_new = (1-relaxation).*h_old + relaxation.*fitted;
            bad = ~isfinite(real(h_new)) | ~isfinite(imag(h_new)) | ...
                abs(h_new)<0.05;
            h_new(bad) = h_old(bad);
        end
        function [csi, data_m, checksum_m, iter_info] = extract_csi( ...
                self, sig, max_iter, opts)
            %EXTRACT_CSI Phase 3 decision-directed complex LoRa sensing CSI.
            %   [CSI,DATA,CRC,ITERINFO] = EXTRACT_CSI(PHY, IQ, 5, OPTS)
            %   first runs the existing iterative_soft_receive() (Algorithm 2).
            %   Only its selected confidence chirps are treated as pilots.
            %   Reconstruct the transmitted chirp, then remove its modulation
            %   by R(t)/Ref(t), approximating SenLoRa Eq. (15).
            %   CSI contains complex per-chirp estimates, amplitude, phase,
            %   packet-relative CFO correction, static-centered CSI, and
            %   adjacent-pilot differences (Eq. (16) approximation).
            %
            %   OPTS: iter_opts(struct), guard_samples(2),
            %         cfo_correction(true), remove_static(true).
            
            %
            %   SCOPE: Scalar flat-channel CSI is a research approximation.
            
            if nargin < 3 || isempty(max_iter)
                max_iter = 5;
            end
            if nargin < 4 || isempty(opts)
                opts = struct();
            end
            if ~isstruct(opts) || ~isscalar(opts)
                error('CSI OPTS must be a scalar struct.');
            end
            if ~isfield(opts,'iter_opts'), opts.iter_opts = struct(); end
            if ~isfield(opts,'guard_samples'), opts.guard_samples = 2; end
            if ~isfield(opts,'cfo_correction')
                opts.cfo_correction = true;
            end
            if ~isfield(opts,'remove_static'), opts.remove_static = true; end
            if ~isstruct(opts.iter_opts) || ~isscalar(opts.iter_opts)
                error('OPTS.iter_opts must be a scalar struct.');
            end
            validateattributes(opts.guard_samples,{'numeric'}, ...
                {'scalar','integer','nonnegative','finite', ...
                '<',self.sample_num/4});
            if ~isscalar(opts.cfo_correction) || ...
                    ~islogical(opts.cfo_correction)
                error('OPTS.cfo_correction must be scalar logical.');
            end
            if ~isscalar(opts.remove_static) || ...
                    ~islogical(opts.remove_static)
                error('OPTS.remove_static must be scalar logical.');
            end

            [data_m,checksum_m,iter_info] = ...
                self.iterative_soft_receive(sig,max_iter,opts.iter_opts);

            % self.sig is now the continuous capture resampled to 2*BW.
            Fs2 = 2*self.bw;
            N = self.sample_num;
            header_n = self.sf-2;
            csi = struct('packet_start_sample',{},'packet_time_s',{}, ...
                'sample_rate_hz',{},'cfo_est_hz',{}, ...
                'cfo_est_valid',{},'pilot_indices',{}, ...
                'pilot_times_s',{},'decoded_symbols',{}, ...
                'raw_csi',{},'corrected_csi',{}, ...
                'amplitude',{},'phase_rad',{}, ...
                'static_reference',{},'static_removed_csi',{}, ...
                'adjacent_difference',{},'pilot_samples_csi',{}, ...
                'pilot_sample_mask',{},'pilot_confidence',{});
            for pkt = 1:numel(iter_info)
                rec = iter_info(pkt);
                x = double(rec.packet_start_sample);
                nSym = double(rec.packet_num_symbols);
                cr_here = double(rec.packet_cr);
                rdd = 4+cr_here;
                ppm = self.sf-2*self.ldr;
                nBlocks = (nSym-8)/rdd;
                needed = header_n+nBlocks*ppm;
                codes = uint16(rec.decoded_codewords(:));
                if nBlocks ~= floor(nBlocks) || numel(codes) ~= needed
                    error('CSI: inconsistent iterative codeword count.');
                end

                % Reconstruct physical chirp symbols with ORIGINAL
                % interleaving and Gray mapping; no hard decoder altered.
                mapped = self.diag_interleave(codes(1:header_n),8);
                for block = 1:nBlocks
                    p = header_n+(block-1)*ppm+1;
                    mapped = [mapped; self.diag_interleave( ...
                        codes(p:p+ppm-1),rdd)]; %#ok<AGROW>
                end
                decoded = double(self.gray_decoding(mapped));
                if numel(decoded) ~= nSym
                    error('CSI: reconstructed chirp count mismatch.');
                end

                chosen = double(rec.selected_symbols(:));
                chosen = chosen(chosen>=9 & chosen<=nSym & ...
                    chosen == floor(chosen));
                chosen = unique(chosen,'stable');
                K = numel(chosen);
                raw_h = complex(nan(K,1),nan(K,1));
                corrected_h = complex(nan(K,1),nan(K,1));
                samples_csi = complex(nan(N,K),nan(N,K));
                masks = false(N,K);
                times = nan(K,1);

                cfo_est = double(rec.packet_cfo_hz);
                valid_cfo = false;
                if opts.cfo_correction
                    [cfo_est,valid_cfo] = ...
                        self.senlora_estimate_preamble_cfo( ...
                        x,rec.packet_cfo_hz);
                else
                    cfo_est = 0;
                end
                for k = 1:K
                    j = chosen(k);
                    sample_idx = (x+(j-1)*N)+(0:N-1)';
                    if sample_idx(1)<1 || ...
                            sample_idx(end)>numel(self.sig)
                        error('CSI pilot extends outside input capture.');
                    end
                    received = self.sig(sample_idx);
                    reference = LoRaPHY.chirp(true,self.sf,self.bw, ...
                        Fs2,decoded(j),0,0);
                    reference = reference(:);
                    if numel(reference)~=N
                        error('CSI chirp reference length mismatch.');
                    end
                    mask = true(N,1);
                    guard = double(opts.guard_samples);
                    if guard > 0
                        mask(1:guard) = false;
                        mask(end-guard+1:end) = false;
                        % The modulated chirp wraps at t=(M-s)/BW.
                        % Exclude samples around that wrap transition.
                        M = 2^self.sf;
                        jump = round(2*(M-decoded(j)))+1;
                        if jump>=1 && jump<=N
                            mask(max(1,jump-guard): ...
                                min(N,jump+guard)) = false;
                        end
                    end
                    if ~any(mask)
                        error('CSI: no usable samples after guard.');
                    end
                    ratio = received./reference;
                    raw_h(k) = mean(ratio(mask));
                    % Correct the phase ramp within this packet only.
                    relative_time = ((j-1)*N+(0:N-1)')/Fs2;
                    corrected_ratio = ratio.* ...
                        exp(-1i*2*pi*cfo_est*relative_time);
                    corrected_h(k) = mean(corrected_ratio(mask));
                    corrected_ratio(~mask) = NaN+1i*NaN;
                    samples_csi(:,k) = corrected_ratio;
                    masks(:,k) = mask;
                    times(k) = (x-1+(j-0.5)*N)/Fs2;
                end
                if K>0 && opts.remove_static
                    static_ref = mean(corrected_h);
                    centered = corrected_h-static_ref;
                else
                    static_ref = complex(NaN,NaN);
                    centered = corrected_h;
                end
                % Only adjacent physical chirps represent an Eq.(16)-like
                % unit-step difference. Nonadjacent selections remain NaN.
                differences = complex(nan(K,1),nan(K,1));
                if K>1
                    adjacent = find(diff(chosen)==1)+1;
                    differences(adjacent) = corrected_h(adjacent)- ...
                        corrected_h(adjacent-1);
                end
                report.packet_start_sample = x;
                report.packet_time_s = (x-1)/Fs2;
                report.sample_rate_hz = Fs2;
                report.cfo_est_hz = cfo_est;
                report.cfo_est_valid = valid_cfo;
                report.pilot_indices = chosen;
                report.pilot_times_s = times;
                report.decoded_symbols = decoded;
                report.raw_csi = raw_h;
                report.corrected_csi = corrected_h;
                report.amplitude = abs(corrected_h);
                report.phase_rad = angle(corrected_h);
                report.static_reference = static_ref;
                report.static_removed_csi = centered;
                report.adjacent_difference = differences;
                report.pilot_samples_csi = samples_csi;
                report.pilot_sample_mask = masks;
                report.pilot_confidence = rec.confidence(chosen);
                csi(end+1) = report; %#ok<AGROW>
            end
        end

        function [freq_hz,valid] = senlora_estimate_preamble_cfo( ...
                self, packet_start_sample, coarse_hz)
            %SENLORA_ESTIMATE_PREAMBLE_CFO Inter-chirp phase-difference CFO.
            %   Consecutive identical preamble chirps cancel their common
            %   LoRa modulation. Their phase difference estimates the CFO
            %   modulo 1/chirp_duration; coarse sync CFO resolves aliases.
            %   This is an approximation, NOT the paper's STO/CFO solver.
            N = self.sample_num;
            Fs2 = 2*self.bw;
            first = round(packet_start_sample- ...
                (self.preamble_len+4.25)*N);
            count = self.preamble_len;
            freq_hz = double(coarse_hz);
            valid = false;
            if first<1 || first+count*N-1>numel(self.sig) || ...
                    count<2
                return;
            end
            phasor = 0;
            for j = 1:count-1
                first_idx = first+(j-1)*N;
                a = self.sig(first_idx:first_idx+N-1);
                b = self.sig(first_idx+N:first_idx+2*N-1);
                phasor = phasor + sum(conj(a).*b);
            end
            if ~isfinite(real(phasor)) || ...
                    ~isfinite(imag(phasor)) || abs(phasor)<eps
                return;
            end
            period = N/Fs2;
            wrapped = angle(phasor)/(2*pi*period);
            alias_spacing = 1/period;
            freq_hz = wrapped + round((coarse_hz-wrapped)/ ...
                alias_spacing)*alias_spacing;
            valid = true;
        end

